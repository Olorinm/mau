import assert from 'node:assert/strict';
import { chromium } from '@playwright/test';
export async function checkBrowser(url) {
 const browser = await chromium.launch({headless:true});
 try {
  const page=await browser.newPage({viewport:{width:1360,height:900}});
  const errors=[];const calls=[];
  page.on('pageerror',error=>errors.push(error.message));
  page.on('request',request=>{if(['fetch','xhr','websocket','eventsource'].includes(request.resourceType())) calls.push(request.url())});
  await page.goto(url);await page.getByRole('button',{name:'Research'}).click();
  await page.getByText('Caller supplied message').waitFor();
  await page.getByPlaceholder('Write a message').fill('An independent UI');
  await page.getByRole('button',{name:'Send message',exact:true}).click();
  await page.getByRole('alert').filter({hasText:'Caller rejected delivery'}).waitFor();
  assert.deepEqual(await page.evaluate(()=>window.actions),[['select','one'],['send','An independent UI']]);
  assert.equal(await page.getByPlaceholder('Write a message').inputValue(),'An independent UI');
  await page.getByRole('button',{name:'catalog',exact:true}).click();
  await page.getByRole('button',{name:'Choose template'}).click();
  await page.getByRole('button',{name:'settings',exact:true}).click();
  await page.getByText('Caller-owned preferences').waitFor();
  await page.getByRole('button',{name:'files',exact:true}).click();
  const editor=page.locator('.cm-content');await editor.waitFor();
  await editor.fill('# Edited by caller');
  await page.getByRole('heading',{name:'Edited by caller'}).waitFor();
  await page.getByRole('button',{name:'rich',exact:true}).click();
  await page.locator('.milkdown .ProseMirror').waitFor();
  await page.locator('.milkdown .ProseMirror').fill('Rich text remains caller owned');
  await page.getByRole('button',{name:'conflict',exact:true}).click();
  await page.getByRole('button',{name:'Use saved version',exact:true}).click();
  await page.getByRole('button',{name:'Save resolution',exact:true}).click();
  assert.deepEqual((await page.evaluate(()=>window.actions)).at(-1),['save','Saved version']);
  await page.getByRole('button',{name:'login',exact:true}).click();
  await page.getByLabel('Account',{exact:true}).fill('sample');
  await page.getByRole('button',{name:'Continue',exact:true}).click();
  await page.getByRole('alert').filter({hasText:'Caller rejected this sign in'}).waitFor();
  await page.screenshot({path:'/tmp/agent-frontend-neutral-auth.png'});
  await page.getByRole('button',{name:'Close form'}).click();
  await page.getByRole('button',{name:'Theme',exact:true}).click();
  await page.screenshot({path:'/tmp/agent-frontend-neutral-desktop.png'});
  await page.setViewportSize({width:390,height:844});
  await page.getByRole('button',{name:'Back',exact:true}).click();
  await page.getByRole('button',{name:'Research'}).waitFor({state:'visible'});
  await page.getByRole('button',{name:'Research'}).click();
  await page.getByPlaceholder('Write a message').waitFor({state:'visible'});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false,'mobile overflow');
  await page.screenshot({path:'/tmp/agent-frontend-neutral-mobile.png'});
  await page.evaluate(()=>window.dispose());
  assert.equal(await page.locator('#root').innerHTML(),'');
  assert.deepEqual(errors,[]);assert.deepEqual(calls,[],'components must not make service requests');
  console.log('Controlled interactions, caller errors, auth layout, file editing, dark/mobile rendering and zero service requests passed.');
 } finally {await browser.close();}
}
