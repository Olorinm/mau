export type Language = "zh-CN" | "en";
export const dictionaries: Record<Language, Record<MessageKey, string>> = { "zh-CN": zh, en };
const languageKey = "mau.language";

export function initialLanguage(): Language {
  const saved = localStorage.getItem(languageKey);
  if (saved === "zh-CN" || saved === "en") return saved;
  return navigator.language.toLowerCase().startsWith("zh") ? "zh-CN" : "en";
}
export function saveLanguage(language: Language) {
  localStorage.setItem(languageKey, language);
  document.documentElement.lang = language;
}

export type Translate = (key: MessageKey, values?: Record<string, string | number>) => string;
export function translator(language: Language): Translate {
  return (key, values) =>
    dictionaries[language][key].replace(/\{(\w+)\}/g, (token, name: string) => String(values?.[name] ?? token));
}
export function errorMessage(t: Translate, code: string): string {
  const key = `error.${code}` as MessageKey;
  return key in zh ? t(key) : t("error.generic", { code });
}

export const I18n = createContext<{ language: Language; t: Translate; setLanguage(language: Language): void }>({
  language: "zh-CN",
  t: translator("zh-CN"),
  setLanguage() {},
});
export const useI18n = () => useContext(I18n);
