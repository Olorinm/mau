export type Language = "zh-CN" | "en";
export const dictionaries: Record<Language, Record<MessageKey, string>> = { "zh-CN": zh, en };
const languageKey = "mau.language";

export function initialLanguage(): Language {
  const saved = localStorage.getItem(languageKey);
  if (saved === "zh-CN" || saved === "en") return saved;
  return navigator.language.toLowerCase().startsWith("zh") ? "zh-CN" : "en";
}
export function saveLanguage(language: Language) {
  localStorage.setItem(languageKey, language);
  document.documentElement.lang = language;
}

export type Translate = (key: MessageKey, values?: Record<string, string | number>) => string;
export function translator(language: Language): Translate {
  // A key the server introduced later (for example a new channel kind) falls back to the other language or the key
  // itself; a missing label must never take down the page.
  return (key, values) =>
    (dictionaries[language][key] ?? dictionaries[language === "zh-CN" ? "en" : "zh-CN"][key] ?? String(key).replace(/^[a-z]+\./, ""))
      .replace(/\{(\w+)\}/g, (token, name: string) => String(values?.[name] ?? token));
}
/** The sentence for an error code, when there is one. */
export function errorSentence(t: Translate, code: string): string | undefined {
  const key = `error.${code}` as MessageKey;
  return key in zh ? t(key) : undefined;
}
export function errorMessage(t: Translate, code: string): string {
  return errorSentence(t, code) ?? t("error.generic", { code });
}

/**
 * What a failed request says. Shared-environment refusals name the partners the server sent beside the code.
 */
export function failureMessage(t: Translate, error: unknown): string {
  if (!(error instanceof ApiError)) return errorMessage(t, "request_failed");
  const { partner, partners } = error.details;
  const names = (partners ?? (partner ? [partner] : [])).map(({ name }) => name).join(t("list.separator"));
  const named = `error.${error.code}.named` as MessageKey;
  return names && named in zh ? t(named, { names }) : errorMessage(t, error.code);
}

export const I18n = createContext<{ language: Language; t: Translate; setLanguage(language: Language): void }>({
  language: "zh-CN",
  t: translator("zh-CN"),
  setLanguage() {},
});
export const useI18n = () => useContext(I18n);
